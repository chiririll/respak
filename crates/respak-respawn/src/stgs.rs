//! `stgs`: a settings object, read from `rpak.asset`. Apex Legends, headers of 72 bytes (v1) and
//! 80 bytes (v2). The value buffer is decoded through the `stlt` layout it names, when that is
//! found; the raw bytes are always kept.
//!
//! Ported from rsx `src/game/rtech/assets/settings.{h,cpp}` (`SettingsAssetHeader_v1_t`,
//! `SettingsAssetHeader_v2_t`, `SettingsMod_s`). rsx picks the header by its size, not by the
//! asset version, and so does this.

use std::collections::HashMap;
use std::sync::Arc;

use async_trait::async_trait;
use bytes::Bytes;
use respak_core::capability::{Dependency, Metadata};
use respak_core::{
    Cx, Data, Detect, Detected, Error, ErrorKind, FormatId, Probe, ReadHandler, Result, Value,
    ValueKey, Version,
};
use serde_json::{json, Map, Value as Json};

use crate::matl_json::{locate, pak_of};
use crate::rmdl::B;
use crate::rpak::{RpakAsset, MEM};
use crate::stlt::{FieldType, Layout, StltAsset};

fn corrupt(context: impl Into<String>) -> Error {
    Error::new(ErrorKind::Corrupt {
        context: context.into(),
    })
}

/// Bytes of a `SettingsMod_s`.
const MOD_LEN: usize = 12;

/// Largest value buffer, name count or mod count taken as plausible.
const LIMIT: u64 = 16 << 20;

/// Nesting limit for arrays inside arrays.
const DEPTH: usize = 8;

/// The fields of the v1 / v2 header.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StgsHeader {
    /// 1 for the 72-byte header, 2 for the 80-byte one.
    pub version: u32,
    /// Guid of the `stlt` that describes the values.
    pub layout: u64,
    /// The value buffer as a `.mem` offset.
    pub values: Option<u64>,
    /// The name as a `.mem` offset.
    pub name: Option<u64>,
    /// The string blob (`mod` strings index into it) as a `.mem` offset.
    pub strings: Option<u64>,
    /// `uniqueID`: generated by the bakery, used as the item flavor id.
    pub unique_id: u32,
    /// The array of mod name pointers.
    pub mod_names: Option<u64>,
    /// The array of [`StgsMod`].
    pub mod_values: Option<u64>,
    /// Bytes of the value buffer.
    pub values_size: u32,
    /// `singlePlayerModCount` (`$modFlags` in rsx).
    pub single_player_mods: u32,
    /// Entries of `mod_names`.
    pub mod_name_count: u32,
    /// Entries of `mod_values`.
    pub mod_value_count: u32,
}

impl StgsHeader {
    /// Parses a relocated header; a length other than 72 or 80 is `UnsupportedVersion`.
    pub fn parse(header: &[u8]) -> Result<Self> {
        let (version, shift) = match header.len() {
            72 => (1, 0),
            80 => (2, 8),
            n => {
                return Err(Error::new(ErrorKind::UnsupportedVersion {
                    format: "stgs".into(),
                    version: format!("header of {n} bytes"),
                }))
            }
        };
        let h = B(header);
        let ptr = |at: usize| -> Result<Option<u64>> {
            let v = h.u64(at)?;
            Ok((v != u64::MAX && v != 0).then_some(v))
        };
        Ok(Self {
            version,
            layout: h.u64(0x00)?,
            values: ptr(0x08)?,
            name: ptr(0x10)?,
            strings: ptr(0x18)?,
            unique_id: h.u32(0x20 + shift)?,
            mod_names: ptr(0x28 + shift)?,
            mod_values: ptr(0x30 + shift)?,
            values_size: h.u32(0x38 + shift)?,
            single_player_mods: h.u32(0x3C + shift)?,
            mod_name_count: h.u32(0x40 + shift)?,
            mod_value_count: h.u32(0x44 + shift)?,
        })
    }
}

/// How a [`StgsMod`] changes its field.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModType {
    /// Adds an int.
    IntAdd,
    /// Multiplies an int.
    IntMultiply,
    /// Adds a float.
    FloatAdd,
    /// Multiplies a float.
    FloatMultiply,
    /// A bool.
    Bool,
    /// An int or a float, depending on the field it targets.
    Number,
    /// A string.
    String,
}

impl ModType {
    fn from_u16(v: u16) -> Option<Self> {
        Some(match v {
            0 => Self::IntAdd,
            1 => Self::IntMultiply,
            2 => Self::FloatAdd,
            3 => Self::FloatMultiply,
            4 => Self::Bool,
            5 => Self::Number,
            6 => Self::String,
            _ => return None,
        })
    }

    /// The name in JSON (rsx spells the multiplies `multipy`; this does not).
    pub fn name(self) -> &'static str {
        match self {
            Self::IntAdd => "int_add",
            Self::IntMultiply => "int_multiply",
            Self::FloatAdd => "float_add",
            Self::FloatMultiply => "float_multiply",
            Self::Bool => "bool",
            Self::Number => "number",
            Self::String => "string",
        }
    }
}

/// One `SettingsMod_s`: a value an item flavor mod writes over a field of the buffer.
#[derive(Debug, Clone, PartialEq)]
pub struct StgsMod {
    /// Index into the mod names.
    pub name_index: u16,
    /// The type, `None` if the file holds a value this reader does not know.
    pub kind: Option<ModType>,
    /// Absolute offset of the target field in the value buffer.
    pub value_offset: u32,
    /// The 4-byte value union as stored.
    pub raw: u32,
    /// The string, for [`ModType::String`].
    pub string: Option<String>,
}

/// A `stgs`: `Data` + `Metadata`.
#[derive(Debug)]
pub struct StgsAsset {
    format: FormatId,
    key: ValueKey,
    header: StgsHeader,
    name: Option<String>,
    guid: u64,
    values: Bytes,
    mod_names: Vec<String>,
    mods: Vec<StgsMod>,
    layout_name: Option<String>,
    settings: Option<Json>,
}

impl StgsAsset {
    /// The parsed header.
    pub fn header(&self) -> &StgsHeader {
        &self.header
    }

    /// The asset guid.
    pub fn guid(&self) -> u64 {
        self.guid
    }

    /// The raw value buffer, laid out by the `stlt`.
    pub fn values(&self) -> &Bytes {
        &self.values
    }

    /// The mod names.
    pub fn mod_names(&self) -> &[String] {
        &self.mod_names
    }

    /// The mod values.
    pub fn mods(&self) -> &[StgsMod] {
        &self.mods
    }

    /// The name of the `stlt`, if it was found.
    pub fn layout_name(&self) -> Option<&str> {
        self.layout_name.as_deref()
    }

    /// The values by field name, `None` when the layout was not found.
    pub fn settings(&self) -> Option<&Json> {
        self.settings.as_ref()
    }
}

impl Metadata for StgsAsset {
    fn name(&self) -> Option<&str> {
        self.name.as_deref()
    }
    fn kind(&self) -> Option<&str> {
        Some("stgs")
    }
    fn guid(&self) -> Option<u64> {
        Some(self.guid)
    }
    fn dependencies(&self) -> Vec<Dependency> {
        match self.header.layout {
            0 => Vec::new(),
            guid => vec![Dependency { guid, name: None }],
        }
    }
}

impl Data for StgsAsset {
    fn format(&self) -> &FormatId {
        &self.format
    }
    fn key(&self) -> &ValueKey {
        &self.key
    }
    fn as_metadata(&self) -> Option<&dyn Metadata> {
        Some(self)
    }
}

/// A float as a JSON number with the digits of its shortest `f32` form.
fn number(v: f32) -> Json {
    format!("{v}")
        .parse::<f64>()
        .ok()
        .and_then(serde_json::Number::from_f64)
        .map_or(Json::Null, Json::Number)
}

/// Decodes the element of `layout` that starts at `base` in `values`. `strings` turns the 8-byte
/// pointer of a string, asset or asset_noprecache value into its text.
fn decode(
    layout: &Layout,
    values: &B<'_>,
    base: usize,
    strings: &mut dyn FnMut([u8; 8]) -> Option<String>,
    depth: usize,
) -> Result<Json> {
    if depth > DEPTH {
        return Err(corrupt("stgs: arrays nest too deep"));
    }
    let mut out = Map::new();
    for f in &layout.fields {
        let at = base + f.offset as usize;
        let v = match f.ty {
            FieldType::Bool => json!(values.get(at, 1)?[0] != 0),
            FieldType::Int => json!(values.i32(at)?),
            FieldType::Float => number(values.f32(at)?),
            FieldType::Float2 => Json::Array(values.floats::<2>(at)?.map(number).to_vec()),
            FieldType::Float3 => Json::Array(values.floats::<3>(at)?.map(number).to_vec()),
            FieldType::String | FieldType::Asset | FieldType::AssetNoPrecache => {
                let slot: [u8; 8] = values.get(at, 8)?.try_into().expect("8 bytes");
                strings(slot).map_or(Json::Null, Json::String)
            }
            FieldType::Array | FieldType::DynamicArray => {
                let sub = layout.subs.get(usize::from(f.sub)).ok_or_else(|| {
                    corrupt(format!("stgs: field `{}` has no sub layout", f.name))
                })?;
                let stride = sub.stride() as usize;
                let (first, count) = if f.ty == FieldType::Array {
                    let align = sub.alignment.max(1) as usize;
                    (
                        at.div_ceil(align) * align,
                        sub.element_count.max(0) as usize,
                    )
                } else {
                    let count = values.i32(at)?.max(0) as usize;
                    (values.u32(at + 4)? as usize, count)
                };
                if stride.saturating_mul(count) > values.0.len() {
                    return Err(corrupt(format!(
                        "stgs: array `{}` of {count} elements does not fit",
                        f.name
                    )));
                }
                let mut items = Vec::with_capacity(count);
                for i in 0..count {
                    items.push(decode(sub, values, first + i * stride, strings, depth + 1)?);
                }
                Json::Array(items)
            }
        };
        out.insert(f.name.clone(), v);
    }
    Ok(Json::Object(out))
}

/// Read edge `rpak.asset -> stgs`.
pub struct StgsRead;

#[async_trait]
impl Detect for StgsRead {
    /// The asset kind is `stgs`; the header size, not the version, picks the layout.
    async fn score(&self, input: &Probe<'_>, _cx: &Cx) -> Result<Option<Detected>> {
        let Some(asset) = input.source.downcast_ref::<RpakAsset>() else {
            return Ok(None);
        };
        Ok((asset.entry.kind == *b"stgs").then(|| Detected {
            score: 10,
            version: Some(Version::new(asset.entry.version)),
        }))
    }
}

/// The NUL-terminated string at `.mem` offset `at` (at most 4 KiB), lossy UTF-8.
async fn string_at(asset: &RpakAsset, at: u64, mem_len: u64) -> Result<String> {
    if at >= mem_len {
        return Err(corrupt("stgs: a string is outside the pak's data"));
    }
    let end = (at + 4096).min(mem_len);
    let bytes = asset.read_mem(at, end - at).await?;
    let nul = bytes
        .iter()
        .position(|&b| b == 0)
        .ok_or_else(|| corrupt("stgs: a string has no end"))?;
    Ok(String::from_utf8_lossy(&bytes[..nul]).into_owned())
}

/// The `stlt` the header names, `None` if it is not in any pak that is searched.
async fn find_layout(guid: u64, source: &Value, cx: &Cx) -> Result<Option<Value>> {
    if guid == 0 {
        return Ok(None);
    }
    let found = match locate(guid, "stlt", &pak_of(source.key()), cx).await {
        Ok(asset) => asset,
        Err(e)
            if matches!(
                e.kind(),
                ErrorKind::NotFound { .. } | ErrorKind::MissingDependency { .. }
            ) =>
        {
            return Ok(None)
        }
        Err(e) => return Err(e),
    };
    cx.mediator
        .identify_as(found, &FormatId::new("stlt"), cx)
        .await
        .map(Some)
}

#[async_trait]
impl ReadHandler for StgsRead {
    /// Parses the header, the name, the value buffer and the mods, and decodes the values when the
    /// layout is found.
    async fn read(&self, source: Value, _detected: &Detected, cx: &Cx) -> Result<Value> {
        let asset = source.downcast_ref::<RpakAsset>().ok_or_else(|| {
            Error::new(ErrorKind::Custom {
                source: None,
                message: "stgs must be read from an rpak.asset".into(),
            })
        })?;
        if asset.entry.kind != *b"stgs" {
            return Err(Error::new(ErrorKind::Custom {
                source: None,
                message: "the asset is not a stgs".into(),
            }));
        }
        let header = StgsHeader::parse(&asset.read_header().await?)?;
        let mem_len = asset.volume.stat(MEM).await?.content_length();

        let name = match header.name {
            Some(at) => string_at(asset, at, mem_len)
                .await
                .ok()
                .filter(|n| !n.is_empty()),
            None => None,
        };

        let values = match header.values {
            Some(at) if header.values_size > 0 => {
                let len = u64::from(header.values_size);
                if len > LIMIT || at.saturating_add(len) > mem_len {
                    return Err(corrupt("stgs: the value buffer is outside the pak's data"));
                }
                asset.read_mem(at, len).await?
            }
            _ => Bytes::new(),
        };

        let count = |n: u32| -> Result<u64> {
            let n = u64::from(n);
            if n > LIMIT {
                return Err(corrupt(format!("stgs: implausible entry count {n}")));
            }
            Ok(n)
        };

        let mut mod_names = Vec::new();
        if let Some(at) = header.mod_names {
            let n = count(header.mod_name_count)?;
            if at.saturating_add(8 * n) > mem_len {
                return Err(corrupt("stgs: the mod names are outside the pak's data"));
            }
            let table = asset.read_mem(at, 8 * n).await?;
            for slot in table.chunks_exact(8) {
                // Pointers inside `.mem` are still stored as `{page, offset}`.
                let text = match asset.mem_offset_of(slot.try_into().expect("8 bytes")) {
                    Some(p) => string_at(asset, p, mem_len).await?,
                    None => String::new(),
                };
                mod_names.push(text);
            }
        }

        let mut mods = Vec::new();
        if let Some(at) = header.mod_values {
            let n = count(header.mod_value_count)?;
            let bytes = MOD_LEN as u64 * n;
            if at.saturating_add(bytes) > mem_len {
                return Err(corrupt("stgs: the mods are outside the pak's data"));
            }
            let table = asset.read_mem(at, bytes).await?;
            let b = B(&table);
            for i in 0..n as usize {
                let base = i * MOD_LEN;
                let kind = ModType::from_u16(b.u16(base + 2)?);
                let raw = b.u32(base + 8)?;
                let string = match (kind, header.strings) {
                    (Some(ModType::String), Some(s)) => {
                        Some(string_at(asset, s + u64::from(raw), mem_len).await?)
                    }
                    _ => None,
                };
                mods.push(StgsMod {
                    name_index: b.u16(base)?,
                    kind,
                    value_offset: b.u32(base + 4)?,
                    raw,
                    string,
                });
            }
        }

        let mut layout_name = None;
        let mut settings = None;
        if let Some(stlt) = find_layout(header.layout, &source, cx).await? {
            let stlt = stlt
                .downcast_ref::<StltAsset>()
                .ok_or_else(|| corrupt("stgs: the layout is not a stlt"))?;
            layout_name = stlt.layout().name.clone();
            // First pass collects the pointers of the text values, the second uses their text.
            let view = B(&values);
            let mut slots: Vec<[u8; 8]> = Vec::new();
            decode(
                stlt.layout(),
                &view,
                0,
                &mut |s| {
                    slots.push(s);
                    None
                },
                0,
            )?;
            let mut texts: HashMap<[u8; 8], String> = HashMap::new();
            for slot in slots {
                if let Some(at) = asset.mem_offset_of(slot) {
                    if let Ok(text) = string_at(asset, at, mem_len).await {
                        texts.insert(slot, text);
                    }
                }
            }
            settings = Some(decode(
                stlt.layout(),
                &view,
                0,
                &mut |s| texts.get(&s).cloned(),
                0,
            )?);
        }

        Ok(Arc::new(StgsAsset {
            format: FormatId::new("stgs").with_version(Version::new(header.version)),
            key: source.key().clone(),
            header,
            name,
            guid: asset.entry.guid,
            values,
            mod_names,
            mods,
            layout_name,
            settings,
        }))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::stlt::Field;

    fn field(name: &str, ty: FieldType, offset: u32, sub: u8) -> Field {
        Field {
            name: name.into(),
            help: String::new(),
            ty,
            offset,
            sub,
        }
    }

    fn layout(fields: Vec<Field>, total: u32, alignment: u32, subs: Vec<Layout>) -> Layout {
        Layout {
            name: None,
            fields,
            element_count: 1,
            total_size: total,
            extra_data_size_index: 0,
            alignment,
            subs,
        }
    }

    #[test]
    fn decodes_scalars_vectors_and_arrays() {
        let mut sub = layout(
            vec![
                field("n", FieldType::Int, 0, 0),
                field("b", FieldType::Bool, 4, 0),
            ],
            5,
            4,
            Vec::new(),
        );
        sub.element_count = 2;
        let root = layout(
            vec![
                field("f", FieldType::Float, 0, 0),
                field("v", FieldType::Float2, 4, 0),
                field("s", FieldType::String, 16, 0),
                field("list", FieldType::Array, 24, 0),
            ],
            40,
            8,
            vec![sub],
        );
        let mut buf = vec![0u8; 40];
        buf[0..4].copy_from_slice(&0.5f32.to_le_bytes());
        buf[4..8].copy_from_slice(&1.0f32.to_le_bytes());
        buf[8..12].copy_from_slice(&2.25f32.to_le_bytes());
        buf[16..24].copy_from_slice(&[1, 0, 0, 0, 8, 0, 0, 0]);
        // Elements are 8 bytes apart (5 aligned to 4 is 8) from offset 24.
        buf[24..28].copy_from_slice(&7i32.to_le_bytes());
        buf[28] = 1;
        buf[32..36].copy_from_slice(&(-3i32).to_le_bytes());
        let json = decode(&root, &B(&buf), 0, &mut |_| Some("txt".into()), 0).unwrap();
        assert_eq!(
            json,
            json!({
                "f": 0.5,
                "v": [1.0, 2.25],
                "s": "txt",
                "list": [{"n": 7, "b": true}, {"n": -3, "b": false}],
            })
        );
    }

    #[test]
    fn dynamic_array_out_of_range_is_corrupt() {
        let element = layout(vec![field("n", FieldType::Int, 0, 0)], 4, 4, Vec::new());
        let root = layout(
            vec![field("list", FieldType::DynamicArray, 0, 0)],
            8,
            4,
            vec![element],
        );
        let mut buf = vec![0u8; 8];
        buf[0..4].copy_from_slice(&1000i32.to_le_bytes());
        buf[4..8].copy_from_slice(&8u32.to_le_bytes());
        assert!(decode(&root, &B(&buf), 0, &mut |_| None, 0).is_err());
    }
}
